def load_events():
    """events.pkl plus calendar columns: date, period ('before'/'after' the estimated break), school_hours flag."""
    ev = pd.read_pickle(WORK / "events.pkl")
    ev["date"] = ev.Timestamp.dt.normalize()
    ev["period"] = np.where(ev.Timestamp >= break_date(), "after", "before")
    ev["school_hours"] = ((ev.hour >= 7) & (ev.hour < 15) & (ev.weekday < 5)).astype(int)
    ev["wkend"] = (ev.weekday >= 5).astype(int)
    return ev


def weighted_km(durations, events, weights, grid):
    """Weighted Kaplan-Meier survival S(t) evaluated on `grid`. `weights` are case weights (e.g. bootstrap counts)."""
    order = np.argsort(durations, kind="stable")
    d, e, w = durations[order], events[order], weights[order]
    at_risk = np.cumsum(w[::-1])[::-1]
    with np.errstate(divide="ignore", invalid="ignore"):
        step = np.where(at_risk > 0, 1 - (w * e) / at_risk, 1.0)
    surv = np.cumprod(step)
    idx = np.searchsorted(d, grid, side="right") - 1
    return np.where(idx >= 0, surv[np.clip(idx, 0, None)], 1.0)
