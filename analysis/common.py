# --------------------------------------------------------------------------- intervals / resampling
def wilson(k, n, z=Z95):
    """Wilson score 95% interval for a proportion k/n."""
    k, n = float(k), float(n)
    if n == 0:
        return np.nan, np.nan
    p = k / n
    den = 1 + z ** 2 / n
    centre = (p + z ** 2 / (2 * n)) / den
    half = z * np.sqrt(p * (1 - p) / n + z ** 2 / (4 * n ** 2)) / den
    return centre - half, centre + half


def cluster_bootstrap(stat, n_clusters, B=2000, chunk=200, seed=SEED):
    """Cluster (student) bootstrap.

    `stat(idx)` receives an integer array idx of shape (b, n_clusters): b bootstrap resamples, each a
    draw WITH replacement of cluster indices. It must return an array whose first axis has length b.
    Returns the B results stacked along axis 0.
    """
    rng = np.random.default_rng(seed)
    out, done = [], 0
    while done < B:
        b = min(chunk, B - done)
        out.append(np.asarray(stat(rng.integers(0, n_clusters, size=(b, n_clusters)))))
        done += b
    return np.concatenate(out, axis=0)


def pct_ci(a, level=95):
    """Percentile interval along axis 0 -> (lower, upper)."""
    lo, hi = np.percentile(a, [(100 - level) / 2, 100 - (100 - level) / 2], axis=0)
    return lo, hi


def bh_qvalues(p):
    """Benjamini-Hochberg false-discovery-rate q-values (monotone), same order as the input."""
    p = np.asarray(p, float)
    n = len(p)
    if n == 0:
        return p
    order = np.argsort(p)
    q = p[order] * n / np.arange(1, n + 1)
    q = np.minimum.accumulate(q[::-1])[::-1]
    out = np.empty(n)
    out[order] = np.clip(q, 0, 1)
    return out


# --------------------------------------------------------------------------- covariates and expected-exit model
DEFAULT_FORMULA = "C(qs) + C(sess) + C(pfail) + C(yg) + C(block) + wkend + lat"


def add_covariates(d):
    """Context covariates for the exit models (all derived from columns made by 00_build_dataset.py).

    qs     question position in the quiz (1-4)
    sess   the student's n-th session on the platform, capped at 5 (1 = first ever session)
    pfail  wrong answers earlier in the same session, capped at 4
    yg     year group, clipped to 5-11 (tiny groups outside that range are merged into the edges)
    block  time of day as recorded: 'school' 07:00-14:59, 'evening' 15:00-22:59, otherwise 'night'
    wkend  1 if Saturday/Sunday
    lat    log(1 + seconds since the previous event in the session, capped at 600 s)  = answering latency
    """
    d = d.copy()
    d["qs"] = d.QuestionSequence.astype(int)
    d["sess"] = d.user_session_idx.clip(upper=5).astype(int)
    d["pfail"] = d.n_prior_fail.clip(upper=4).astype(int)
    d["yg"] = d.YearGroup.fillna(8).clip(5, 11).astype(int)
    h = d.hour
    d["block"] = np.where((h >= 7) & (h < 15), "school", np.where((h >= 15) & (h < 23), "evening", "night"))
    d["wkend"] = (d.weekday >= 5).astype(int)
    d["lat"] = np.log1p(d.latency_s.clip(0, 600).fillna(0))
    return d


def design_matrix(df, formula=None):
    """Patsy design matrix (DataFrame, includes an intercept column)."""
    return patsy.dmatrix(formula or DEFAULT_FORMULA, df, return_type="dataframe")


def expected_prob(X, y, mask):
    """Fit an (unpenalised) logistic regression on the rows where `mask` is True and return the fitted
    exit probability for EVERY row. 'Expected' exits for a group are the sum of these probabilities.

    Columns that are constant-zero inside the fitting sample (a rare category missing from a random
    half of the students) are dropped, which keeps the fit non-singular; a ridge fit is the
    fallback if the IRLS fit fails to converge."""
    import statsmodels.api as sm
    X = np.asarray(X, float)
    y = np.asarray(y, float)
    mask = np.asarray(mask, bool)
    Xm = X[mask]
    ones = (Xm == 1).all(axis=0)
    keep = (np.ptp(Xm, axis=0) > 0) | (ones & (np.cumsum(ones) == 1))      # varying columns + one intercept
    Xk = X[:, keep]
    try:                                     # IRLS (GLM, binomial/logit): converges reliably here
        m = sm.GLM(y[mask], Xk[mask], family=sm.families.Binomial()).fit(maxiter=100)
        if m.converged and np.isfinite(m.params).all():
            return m.predict(Xk)
    except Exception:
        pass
    from sklearn.linear_model import LogisticRegression
    m = LogisticRegression(C=100.0, max_iter=2000, fit_intercept=False).fit(Xk[mask], y[mask])
    return m.predict_proba(Xk)[:, 1]


def oe_table(df, p, key, min_n=30):
    """Observed-vs-expected exits per group `key` (e.g. SubjectId), with student-clustered inference.

    O  observed exits;  E  expected exits = sum of model probabilities p;  oe = O/E
    se = sqrt( sum p(1-p) * max(1, R2/S2) ), where R2 = sum over students of (sum of residuals)^2 and
         S2 = sum of squared residuals: the binomial variance inflated for repeated events by one student
    z = (O-E)/se;  p_one = P(Z > z) (one-sided: 'more exits than expected');  oe_lo/oe_hi = (O -/+ 1.96 se)/E
    q  Benjamini-Hochberg q-value across the groups with n >= min_n (NaN for smaller groups)
    """
    d = pd.DataFrame({key: df[key].values, "UserId": df["UserId"].values,
                      "y": df["is_exit"].values.astype(float), "p": np.asarray(p, float)})
    d["r"] = d.y - d.p
    d["v"] = d.p * (1 - d.p)
    d["r2"] = d.r ** 2
    g = d.groupby(key)
    out = pd.DataFrame({"n": g.size(), "students": g.UserId.nunique(), "O": g.y.sum(), "E": g.p.sum(), "V": g.v.sum(), "S2": g.r2.sum()})
    out["R2"] = d.groupby([key, "UserId"]).r.sum().pow(2).groupby(level=0).sum()
    out["se"] = np.sqrt(out.V * np.maximum(1.0, out.R2 / out.S2))
    out["oe"] = out.O / out.E
    out["oe_lo"] = (out.O - Z95 * out.se) / out.E
    out["oe_hi"] = (out.O + Z95 * out.se) / out.E
    out["raw_rate"] = out.O / out.n
    out["z"] = (out.O - out.E) / out.se
    out["p_one"] = 1 - stats.norm.cdf(out.z)
    ok = (out.n >= min_n).values
    out["q"] = np.nan
    out.loc[ok, "q"] = bh_qvalues(out.p_one.values[ok])
    return out.drop(columns=["V", "S2", "R2"])


